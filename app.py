"""EventMind Streamlit dashboard. CLI remains the official one-command test path."""
import json
from pathlib import Path
import streamlit as st
from eventmind.state import process,save,load,trace_summary

st.set_page_config(page_title='EventMind AI',page_icon='🧠',layout='wide')
st.title('🧠 EventMind AI')
st.caption('Constraint-aware hackathon planner · evidence-backed decisions · real model-call audit')
state_path=Path('outputs/state.json')
if 'state' not in st.session_state:
    st.session_state.state=load(state_path) if state_path.exists() else None

with st.sidebar:
    st.header('Message processing')
    st.info('The first file creates a new plan. Subsequent files add messages and update that plan.')
    uploader=st.file_uploader('Choose text file',type=['txt'],key='packfile')
    fresh=st.checkbox('Start new plan (reset history)',value=st.session_state.state is None)
    if st.button('Process messages',type='primary',disabled=uploader is None,use_container_width=True):
        raw=uploader.getvalue().decode('utf-8-sig')
        try:
            with st.spinner('Reading messages and validating plan...'):
                result=process(raw,None if fresh else st.session_state.state)
            st.session_state.state=result
            save(result,state_path)
            save(result['plan'],'outputs/plan.json')
            save(result['trace'],'outputs/trace.json')
            st.success('Processed; saved plan, trace, and state.')
        except Exception as exc:
            st.error(f'Processing failed: {exc}')
    if st.session_state.state:
        data=json.dumps(st.session_state.state,indent=2,ensure_ascii=False)
        st.download_button('Download complete result JSON',data,'eventmind_result.json','application/json',use_container_width=True)

state=st.session_state.state
if not state:
    st.info('Upload data/sample_messages.txt to generate your first plan. Configure .env with your model API key before processing.')
    st.stop()

p=state['plan']
if state['valid']:
    st.success('Plan passes implemented validation checks')
else:
    st.error('Plan needs attention — see validation warnings')
for warning in state.get('warnings',[]):
    st.warning(warning)

m1,m2,m3,m4=st.columns(4)
m1.metric('Students',f"{p['event']['students']:g}" if p['event']['students'] is not None else 'Unknown')
m2.metric('Teams',f"{p['event']['teams']:g}" if p['event']['teams'] is not None else 'Unknown')
m3.metric('People to feed',f"{p['event']['attendees']:g}" if p['event']['attendees'] is not None else 'Unknown')
m4.metric('Remaining budget',f"Rs {p['budget']['remaining']:,.0f}" if p['budget']['remaining'] is not None else 'Unknown')

tabs=st.tabs(['📍 Venue','🗓 Schedule','🍱 Food','⚖️ Judging','💰 Budget','🚫 Rejections','🔎 Model trace','📚 Evidence'])
with tabs[0]:
    st.subheader('Selected venue')
    st.json(p['venue'])
    st.subheader('Valid offered venues')
    st.dataframe(p['available_venues'],use_container_width=True)
with tabs[1]:
    st.subheader('Event schedule')
    st.dataframe(p['schedule'],use_container_width=True)
    st.caption('Schedule durations are generated by deterministic policy and should be checked against any extra constraints in the unseen pack.')
with tabs[2]:
    st.subheader('Food decision')
    st.json(p['food']['selected'])
    st.write('Required meals:',p['food']['required_meals'])
    st.dataframe(p['food']['options'],use_container_width=True)
with tabs[3]:
    st.subheader('Judging feasibility')
    st.json(p['judging'])
with tabs[4]:
    st.subheader('Budget breakdown')
    st.json(p['budget'])
with tabs[5]:
    st.subheader('Rejected / unapproved requests')
    if state['rejected']:
        for entry in state['rejected']:
            st.error(entry['reason'])
            st.caption(entry['message'])
    else: st.info('No rejected messages so far.')
with tabs[6]:
    st.subheader('Actual API trace')
    totals=trace_summary(state['trace'])
    st.json(totals)
    for entry in state['trace']:
        with st.expander(f"Call #{entry['number']} · {entry['model']} · {entry['area']} · tokens: {entry['total_tokens']}"):
            st.json(entry)
with tabs[7]:
    st.subheader('Source evidence for decisions')
    st.json(p['evidence'])
    if state.get('notes'):
        st.subheader('Extraction notes')
        st.json(state['notes'])
    if p['other_constraints']:
        st.subheader('New/unhandled constraint types')
        st.json(p['other_constraints'])
